"use client";

import { useEffect, useRef, useState } from "react";
import { formatGHS } from "@/lib/money";

/** Money figure that counts smoothly to its new value (display only; the real value is always exact). */
export function AnimatedMoney({ value, sign, compact, duration = 600 }: { value: number; sign?: boolean; compact?: boolean; duration?: number }) {
  const [shown, setShown] = useState(value);
  const from = useRef(value);
  useEffect(() => {
    const start = from.current;
    if (start === value || matchMedia("(prefers-reduced-motion: reduce)").matches) {
      from.current = value;
      setShown(value);
      return;
    }
    const t0 = performance.now();
    let raf = 0;
    const step = (t: number) => {
      const k = Math.min(1, (t - t0) / duration);
      const eased = 1 - Math.pow(1 - k, 3);
      setShown(Math.round(start + (value - start) * eased));
      if (k < 1) raf = requestAnimationFrame(step);
      else from.current = value;
    };
    raf = requestAnimationFrame(step);
    return () => {
      cancelAnimationFrame(raf);
      from.current = value;
    };
  }, [value, duration]);
  return <>{formatGHS(shown, { sign, compact })}</>;
}
